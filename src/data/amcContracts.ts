import { AMCContract, AMCStatus } from '../types';

export const computeContractStatus = (contract: AMCContract): AMCStatus => {
  if (contract.status === 'CANCELLED' || contract.status === 'SUSPENDED' || contract.status === 'PENDING') {
    return contract.status;
  }
  const now = new Date();
  const end = new Date(contract.endDate);
  if (now > end) {
    return 'EXPIRED';
  }
  const diffTime = end.getTime() - now.getTime();
  const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));
  if (diffDays <= 30) {
    return 'EXPIRING_SOON';
  }
  return 'ACTIVE';
};

